  onLoad(options) {
    const id = options.id || '';
    this.setData({ houseId: id });
    this.loadDetail(id);
  },

  async loadDetail(id) {
    this.setData({ loading: true });

    // 优先从云数据库加载
    try {
      if (wx.cloud) {
        const db = wx.cloud.database();
        const res = await db.collection('houses')
          .doc(id)
          .get();

        if (res.data) {
          this.setData({
            house: res.data,
            loading: false
          });
          wx.setNavigationBarTitle({ title: res.data.name || '家族详情' });
          return;
        }
      }
    } catch (err) {
      console.log('云数据库加载失败，使用本地数据', err);
    }

    // 降级：本地数据
    const localHouse = this.getLocalHouseDetail(id);
    this.setData({
      house: localHouse,
      loading: false
    });
    if (localHouse) {
      wx.setNavigationBarTitle({ title: localHouse.name || '家族详情' });
    }
  },

