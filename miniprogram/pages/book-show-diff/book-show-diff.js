  async loadDiffData() {
    this.setData({ loading: true });

    // 尝试从云数据库加载
    try {
      if (wx.cloud) {
        const db = wx.cloud.database();
        // 尝试获取差异数据集合
        const res = await db.collection('book_show_diffs')
          .limit(50)
          .get();

        if (res.data && res.data.length > 0) {
          const characterDiffs = res.data.filter(d => d.category === 'character');
          const plotDiffs = res.data.filter(d => d.category === 'plot');
          const cutCharacters = res.data.filter(d => d.category === 'cut');
          this.setData({ characterDiffs, plotDiffs, cutCharacters, loading: false });
          return;
        }
      }
    } catch (err) {
      console.log('云数据库加载失败，使用本地数据', err);
    }

    // 降级：使用本地完整数据
    const localData = this.getLocalDiffData();
    this.setData({
      characterDiffs: localData.characterDiffs,
      plotDiffs: localData.plotDiffs,
      cutCharacters: localData.cutCharacters,
      loading: false
    });
  },

